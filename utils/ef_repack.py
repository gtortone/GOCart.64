#!/usr/bin/env python3
"""
ef_repack.py - Repack EasyLoader (EasyFS) EasyFlash .crt compilations into
several smaller .crt files, each with its own consistent EasyLoader menu.

For each input cartridge:
  1. "ndeft dump" extracts every menu entry plus boot code, loader and EAPI
     together with an LST file.
  2. Menu entries are distributed, in their original order, into parts.
     Each part is rebuilt with "ndeft make" and its real file size checked;
     an entry that would push a part over --max-size starts a new part.
  3. Boot code, loader, EAPI and special "!el_" entries (autoboot, screen
     saver) are copied into every part.

Requires ndeft (from ndefpack) in PATH or given with --ndeft.

Usage:
    ef_repack.py [options] <file.crt | directory> [...]
"""

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# LST item types that are system parts (boot code, loader, EAPI)
SYSTEM_TYPES = {"n", "N", "o", "O", "e"}
# Special EasyLoader entry names copied into every part
SPECIAL_PREFIX = "!el_"
EF_NAME_MAX = 16


class NdeftError(Exception):
    pass


def run_ndeft(ndeft, args, cwd):
    result = subprocess.run([ndeft, *args], cwd=cwd,
                            capture_output=True, text=True, errors="replace")
    if result.returncode != 0:
        output = (result.stdout + result.stderr).strip()
        raise NdeftError(f"ndeft {' '.join(args)} failed:\n{output}")
    return result.stdout


def get_ef_name(ndeft, crt_path, cwd):
    out = run_ndeft(ndeft, ["list", str(crt_path)], cwd)
    m = re.search(r"Listing cart '(.*)'; mode", out)
    return m.group(1) if m else crt_path.stem


def read_lst(lst_path):
    """Return the list of item lines (comments and blank lines removed)."""
    items = []
    for line in lst_path.read_text(errors="replace").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            items.append(line)
    return items


def item_fields(item):
    # FILE[,NAME[,TYPE]] - FILE never contains commas (generated by dump)
    parts = item.split(",")
    file_name = parts[0]
    item_type = ""
    name = ""
    if len(parts) >= 3 and parts[-1] in SYSTEM_TYPES | {"t", "h", "a"}:
        item_type = parts[-1]
        name = ",".join(parts[1:-1])
    elif len(parts) >= 2:
        name = ",".join(parts[1:])
    return file_name, name, item_type


def is_common(item):
    _, name, item_type = item_fields(item)
    return item_type in SYSTEM_TYPES or name.startswith(SPECIAL_PREFIX)


def build_part(ndeft, work_dir, items, ef_name, out_path):
    # ndeft cannot parse names containing commas in an LST file (even the
    # ones written by its own "dump"), so such entries get a temporary name
    # and are renamed afterwards with "ndeft ren".
    lst_lines = []
    renames = []        # (entry index, real name)
    entry_index = 0
    for item in items:
        file_name, name, item_type = item_fields(item)
        if item_type not in SYSTEM_TYPES:
            if "," in name:
                temp_name = f"_ren{len(renames)}"
                renames.append((entry_index, name))
                item = f"{file_name},{temp_name}" + (f",{item_type}" if item_type else "")
            entry_index += 1
        lst_lines.append(item)

    lst = work_dir / "part.lst"
    lst.write_text("\n".join(lst_lines) + "\n")
    run_ndeft(ndeft, ["-q", "-o", str(out_path), "-e", ef_name, "make", lst.name], work_dir)
    for index, real_name in renames:
        run_ndeft(ndeft, ["-q", "ren", str(out_path), str(index), real_name], work_dir)
    return out_path.stat().st_size


def part_name(ef_name, index):
    suffix = f" {index}"
    return ef_name[:EF_NAME_MAX - len(suffix)] + suffix


def process(crt_path, args):
    crt_path = crt_path.resolve()
    out_dir = Path(args.out_dir).resolve() if args.out_dir else crt_path.parent
    out_dir.mkdir(parents=True, exist_ok=True)

    with tempfile.TemporaryDirectory(prefix="efrepack_") as tmp:
        work_dir = Path(tmp)
        ef_name = get_ef_name(args.ndeft, crt_path, work_dir)
        run_ndeft(args.ndeft, ["-q", "dump", str(crt_path), "d"], work_dir)
        all_items = read_lst(work_dir / "d.lst")

        common = [i for i in all_items if is_common(i)]
        entries = [i for i in all_items if not is_common(i)]
        if not entries:
            raise NdeftError("no menu entries found")

        probe = work_dir / "probe.crt"
        parts = []          # list of entry lists
        current = []
        for entry in entries:
            candidate = current + [entry]
            size = build_part(args.ndeft, work_dir, common + candidate,
                              ef_name, probe)
            if size <= args.max_size or not current:
                if size > args.max_size:
                    print(f"  WARNING: entry '{item_fields(entry)[1]}' alone "
                          f"gives {size} bytes (> --max-size)", file=sys.stderr)
                current = candidate
            else:
                parts.append(current)
                current = [entry]
        parts.append(current)

        if args.parts and len(parts) > args.parts:
            raise NdeftError(f"needs {len(parts)} parts, more than --parts {args.parts}")

        print(f"{crt_path.name} ('{ef_name}'): {len(entries)} entries, "
              f"{crt_path.stat().st_size} bytes -> {len(parts)} part(s)")

        for idx, part in enumerate(parts, start=1):
            out = out_dir / f"{crt_path.stem}_part{idx}.crt"
            size = build_part(args.ndeft, work_dir, common + part,
                              part_name(ef_name, idx), out)
            first = item_fields(part[0])[1]
            last = item_fields(part[-1])[1]
            print(f"  part {idx}: {len(part)} entries ({first} .. {last}), "
                  f"{size} bytes -> {out.name}")


def main():
    parser = argparse.ArgumentParser(
        description="Repack EasyLoader EasyFlash .crt files into smaller parts")
    parser.add_argument("inputs", nargs="+", help=".crt files or directories")
    parser.add_argument("--max-size", type=int, default=350 * 1024,
                        help="max size of each output .crt in bytes (default 358400)")
    parser.add_argument("--parts", type=int, default=0,
                        help="fail if more than this many parts are needed (0 = no limit)")
    parser.add_argument("--ndeft", default="ndeft", help="path to the ndeft executable")
    parser.add_argument("-o", "--out-dir", help="output directory (default: next to input)")
    args = parser.parse_args()

    ndeft_path = shutil.which(args.ndeft)
    if not ndeft_path:
        sys.exit(f"ndeft not found: {args.ndeft}")
    args.ndeft = str(Path(ndeft_path).resolve())

    files = []
    for item in args.inputs:
        p = Path(item)
        if p.is_dir():
            files += sorted(f for f in p.iterdir()
                            if f.suffix.lower() == ".crt" and "_part" not in f.stem)
        else:
            files.append(p)

    errors = 0
    for f in files:
        try:
            process(f, args)
        except (NdeftError, OSError) as e:
            print(f"{f.name}: ERROR: {e}", file=sys.stderr)
            errors += 1
    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
